"""Smart University dashboard.  Run with:  streamlit run app.py"""
import os
import time
from datetime import datetime

import pandas as pd
import streamlit as st

import config
from src.adapters import (
    adapt_attendance_data,
    adapt_classroom_data,
    adapt_parking_data,
)
from src.data_logger import data_logger
from src.simulator import HardwareSimulator
from src.state import system_state

SIMULATION = not config.HARDWARE_MODE

st.set_page_config(page_title="Smart University System", page_icon="🎓", layout="wide")


@st.cache_resource
def start_hardware():
    """Starts the ESP32 serial readers once, inside the dashboard process,
    so the readings land in the same system_state the dashboard displays."""
    from src.serial_manager import SerialManager

    manager = SerialManager(baud_rate=config.BAUD_RATE)
    manager.connect("parking", config.PARKING_PORT)
    manager.connect("classroom", config.CLASSROOM_PORT)
    return manager


def load_history(module):
    path = os.path.join(config.DATA_DIR, f"{module}_history.csv")
    if not os.path.isfile(path):
        return None
    try:
        return pd.read_csv(path)
    except (pd.errors.ParserError, pd.errors.EmptyDataError, UnicodeDecodeError):
        return None


# ---------------------------------
# DATA SOURCE: simulator or real hardware
# ---------------------------------
simulator = None
manager = None
if SIMULATION:
    if "simulator" not in st.session_state:
        st.session_state.simulator = HardwareSimulator()
    simulator = st.session_state.simulator
else:
    manager = start_hardware()

# ---------------------------------
# SIDEBAR
# ---------------------------------
st.sidebar.title("🎓 Smart University")
st.sidebar.write("University Monitoring System")

if SIMULATION:
    st.sidebar.success("Simulation mode")
    st.sidebar.caption("ESP32 boards are not required.")
else:
    st.sidebar.success("Hardware mode")
    for name, connected in manager.get_status().items():
        label = f"{name}: {'connected' if connected else 'disconnected'}"
        (st.sidebar.success if connected else st.sidebar.error)(label)

st.sidebar.divider()

if SIMULATION and st.sidebar.button("Reset simulation"):
    system_state.reset()
    st.session_state.simulator = HardwareSimulator()
    st.rerun()

if st.sidebar.button("Clear history files"):
    data_logger.clear()
    st.rerun()

auto_refresh = st.sidebar.checkbox(
    "Auto-refresh every 2 seconds", value=config.HARDWARE_MODE
)

# ---------------------------------
# CURRENT DATA
# ---------------------------------
raw = system_state.get_all()["data"]
parking = adapt_parking_data(raw["parking"])
attendance = adapt_attendance_data(raw["attendance"])
classroom = adapt_classroom_data(raw["classroom"])

parking_history = load_history("parking")
attendance_history = load_history("attendance")
classroom_history = load_history("classroom")

recorded_total = 0
if attendance_history is not None and "attendance_recorded" in attendance_history:
    recorded_total = int((attendance_history["attendance_recorded"].astype(str) == "True").sum())

# ---------------------------------
# HEADER AND METRICS
# ---------------------------------
st.title("🎓 Smart University Dashboard")
st.write("Monitor university parking, student attendance and classroom access in one place.")
st.caption("Last dashboard refresh: " + datetime.now().strftime("%Y-%m-%d %H:%M:%S"))
if SIMULATION:
    st.info("Simulation mode: all readings are generated by software.")
st.divider()

col1, col2, col3, col4 = st.columns(4)
col1.metric("Available Parking", parking["available_spaces"])
col2.metric("Occupied Parking", parking["occupied_spaces"])
col3.metric("Attendance Recorded (total)", recorded_total)
col4.metric("Latest Access", classroom["access_status"].replace("Access ", "").replace(
    "Waiting for verification", "Waiting"))
st.divider()

overview_tab, parking_tab, attendance_tab, classroom_tab, history_tab = st.tabs(
    ["Overview", "Parking", "Attendance", "Classroom Access", "History"]
)

# ---------------------------------
# OVERVIEW
# ---------------------------------
with overview_tab:
    left, right = st.columns(2)
    with left:
        st.write("### Parking Summary")
        st.write(f"Total spaces: {parking['total_spaces']}")
        st.write(f"Available: {parking['available_spaces']}")
        st.write(f"Occupied: {parking['occupied_spaces']}")
        if parking["total_spaces"] > 0:
            st.progress(parking["occupied_spaces"] / parking["total_spaces"])
            st.caption("Parking occupancy")
    with right:
        st.write("### Classroom Summary")
        st.write(f"Person detected nearby: {classroom['person_near']}")
        st.write(f"Door state: {classroom['door_state']}")
        st.write(f"Access result: {classroom['access_status']}")

# ---------------------------------
# PARKING
# ---------------------------------
with parking_tab:
    st.subheader("University Parking")

    if SIMULATION:
        st.write("### Simulate a Car")
        space = st.selectbox("Select a parking space", list(simulator.spaces))
        c1, c2 = st.columns(2)
        if c1.button("🚗 Park Car"):
            if simulator.park_car(space):
                st.rerun()
            st.error("This space is already occupied.")
        if c2.button("Remove Car"):
            if simulator.remove_car(space):
                st.rerun()
            st.error("This space is already available.")
        st.divider()

    c1, c2, c3 = st.columns(3)
    c1.metric("Available Spaces", parking["available_spaces"])
    c2.metric("Occupied Spaces", parking["occupied_spaces"])
    c3.metric("Parked Cars", parking["parked_cars_count"])

    st.write("### Individual Parking Spaces")
    grid = st.columns(3)
    for index, space_info in enumerate(parking["spaces"]):
        with grid[index % 3]:
            if space_info["status"] == "occupied":
                st.error(f"{space_info['space_id']} - Occupied")
            else:
                st.success(f"{space_info['space_id']} - Available")

    st.write("### Sensor Information")
    st.write(f"Pressure sensors reporting occupied: {parking['pressure_occupied_count']}")

# ---------------------------------
# ATTENDANCE
# ---------------------------------
with attendance_tab:
    st.subheader("Student Attendance")

    if SIMULATION:
        st.write("### Simulate Face Recognition")
        student_id = st.text_input("Student ID", value="S001")
        student_name = st.text_input("Student Name", value="Ahmed")
        c1, c2 = st.columns(2)
        if c1.button("Recognize Student"):
            if student_id.strip() and student_name.strip():
                simulator.record_attendance(student_id.strip(), student_name.strip())
                st.rerun()
            st.error("Please enter the student ID and name.")
        if c2.button("Simulate Unknown Student"):
            simulator.unknown_student()
            st.rerun()
        st.divider()

    st.write("### Latest Attendance Result")
    if attendance["recognized"]:
        st.success("Student recognized")
        st.write(f"**Student ID:** {attendance['student_id']}")
        st.write(f"**Student Name:** {attendance['student_name']}")
    else:
        st.warning("No recognized student")

    if attendance["attendance_recorded"]:
        st.success("Attendance recorded")
    else:
        st.warning("Attendance has not been recorded")

    st.write(f"**Status:** {attendance['status']}")
    st.write(f"**Timestamp:** {attendance['timestamp'] or 'Not available'}")
    st.write(f"**Session:** {attendance['session_id'] or 'Not available'}")

# ---------------------------------
# CLASSROOM ACCESS
# ---------------------------------
with classroom_tab:
    st.subheader("Classroom Access Control")

    if SIMULATION:
        st.write("### Simulate Classroom Sensors")
        distance = st.slider("Ultrasonic distance (cm)", 0, 200, 25)
        st.caption(f"A person is nearby when the distance is {config.PERSON_NEAR_CM} cm or less.")
        rfid_valid = st.checkbox("Valid RFID card")
        fingerprint_valid = st.checkbox("Valid fingerprint")
        face_recognized = st.checkbox("Face recognized")
        if st.button("Evaluate Classroom Access"):
            simulator.update_classroom(distance, rfid_valid, fingerprint_valid, face_recognized)
            st.rerun()
        st.divider()

    st.write("### Sensor Readings")
    c1, c2 = st.columns(2)
    with c1:
        distance_text = (
            f"{classroom['distance_cm']} cm"
            if classroom["distance_cm"] is not None
            else "No reading"
        )
        st.metric("Distance from Door", distance_text)
        st.write(f"Person nearby: {classroom['person_near']}")
        st.write(f"RFID valid: {classroom['rfid_valid']}")
        st.write(f"Fingerprint valid: {classroom['fingerprint_valid']}")
        st.write(f"Face recognized: {classroom['face_recognized']}")
    with c2:
        st.write("### Access Decision")
        if classroom["access_granted"] is True:
            st.success("ACCESS GRANTED")
        elif classroom["access_granted"] is False:
            st.error("ACCESS DENIED")
        else:
            st.warning("Waiting for verification")
        st.write(f"Door state: {classroom['door_state']}")

# ---------------------------------
# HISTORY
# ---------------------------------
with history_tab:
    st.subheader("System Data History")
    st.write("Records saved automatically in the data/ folder (newest first).")

    for title, history in (
        ("Parking History", parking_history),
        ("Attendance History", attendance_history),
        ("Classroom Access History", classroom_history),
    ):
        st.divider()
        st.write(f"### {title}")
        if history is None or history.empty:
            st.info("No records yet.")
            continue
        st.dataframe(history.iloc[::-1], hide_index=True)

        if title == "Parking History" and {"timestamp", "available_spaces",
                                           "occupied_spaces"} <= set(history.columns):
            chart = history.copy()
            chart["timestamp"] = pd.to_datetime(chart["timestamp"], errors="coerce")
            chart = chart.dropna(subset=["timestamp"]).sort_values("timestamp")
            st.write("#### Parking Availability Over Time")
            st.line_chart(chart.set_index("timestamp")[["available_spaces", "occupied_spaces"]])

st.divider()
st.caption("Smart University System | Data Acquisition System Graduation Project")

# Live refresh so real ESP32 readings appear without clicking
if auto_refresh:
    time.sleep(2)
    st.rerun()
